public class two_add {
    public static void main(String[] args) {
        int a = 5;
        int b = 10;
        int c = 15;
        int d = 20;
        int sum = addTwoNumbers(a, b, c, d);
        System.out.println("The sum of " + a + ", " + b + ", " + c + " and " + d + " is: " + sum);
    }

    public static int addTwoNumbers(int num1, int num2, int num3, int num4) {
        return num1 + num2 + num3 + num4;
    }
}

